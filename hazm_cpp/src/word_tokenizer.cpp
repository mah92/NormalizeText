WordTokenizer::WordTokenizer(const std::string& words_file,
                             const std::string& verbs_file,
                             bool join_verb_parts) {
    // Load words
    std::string wf = words_file.empty() ? data_path("words.dat") : words_file;
    words = load_words(wf);
    
    // Initialize verb parts if needed
    if (join_verb_parts) {
        std::string vf = verbs_file.empty() ? data_path("verbs.dat") : verbs_file;
        init_verb_parts(vf);
    }
}

